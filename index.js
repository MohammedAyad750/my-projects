/* =========================================================
   26. نظام النوافذ المنبثقة Modal
   ========================================================= */

function initializeModalSystem() {


    const projectButtons =
        document.querySelectorAll(
            ".project-details-btn"
        );


    const projectModals =
        document.querySelectorAll(
            ".project-modal"
        );


    /* -----------------------------------------------------
       فتح المشروع
       ----------------------------------------------------- */

    projectButtons.forEach(
        function (button) {

            button.addEventListener(
                "click",
                function () {

                    const projectId =
                        button.getAttribute(
                            "data-project"
                        );


                    if (!projectId) {

                        return;

                    }


                    const modal =
                        document.getElementById(
                            projectId
                        );


                    if (!modal) {

                        console.warn(
                            "Project modal not found:",
                            projectId
                        );

                        return;

                    }


                    openModal(modal);

                }
            );

        }
    );


    /* -----------------------------------------------------
       أزرار الإغلاق
       ----------------------------------------------------- */

    projectModals.forEach(
        function (modal) {

            const closeButton =
                modal.querySelector(
                    ".modal-close"
                );


            if (closeButton) {

                closeButton.addEventListener(
                    "click",
                    function () {

                        closeModal(modal);

                    }
                );

            }


            /* -------------------------------------------------
               إغلاق عند الضغط على الخلفية
               ------------------------------------------------- */

            const overlay =
                modal.querySelector(
                    ".modal-overlay"
                );


            if (overlay) {

                overlay.addEventListener(
                    "click",
                    function () {

                        closeModal(modal);

                    }
                );

            }


            /* -------------------------------------------------
               منع إغلاق النافذة عند الضغط على المحتوى
               ------------------------------------------------- */

            const content =
                modal.querySelector(
                    ".modal-content"
                );


            if (content) {

                content.addEventListener(
                    "click",
                    function (event) {

                        event.stopPropagation();

                    }
                );

            }

        }
    );


    /* -----------------------------------------------------
       ESC لإغلاق النافذة
       ----------------------------------------------------- */

    document.addEventListener(
        "keydown",
        function (event) {

            if (
                event.key !==
                "Escape"
            ) {

                return;

            }


            const activeModal =
                document.querySelector(
                    ".project-modal.active"
                );


            if (activeModal) {

                closeModal(
                    activeModal
                );

            }

        }
    );

}


/* =========================================================
   27. فتح Modal
   ========================================================= */

function openModal(modal) {


    if (!modal) {

        return;

    }


    /* -----------------------------------------------------
       إغلاق أي نافذة أخرى
       ----------------------------------------------------- */

    const allModals =
        document.querySelectorAll(
            ".project-modal"
        );


    allModals.forEach(
        function (item) {

            item.classList.remove(
                "active"
            );


            item.setAttribute(
                "aria-hidden",
                "true"
            );

        }
    );


    /* -----------------------------------------------------
       فتح النافذة المطلوبة
       ----------------------------------------------------- */

    modal.classList.add(
        "active"
    );


    modal.setAttribute(
        "aria-hidden",
        "false"
    );


    /* -----------------------------------------------------
       منع تمرير الصفحة
       ----------------------------------------------------- */

    document.body.classList.add(
        "modal-open"
    );


    /* -----------------------------------------------------
       إعادة المحتوى إلى الأعلى
       ----------------------------------------------------- */

    const modalContent =
        modal.querySelector(
            ".modal-content"
        );


    if (modalContent) {

        modalContent.scrollTop =
            0;

    }


    /* -----------------------------------------------------
       التركيز على زر الإغلاق
       ----------------------------------------------------- */

    const closeButton =
        modal.querySelector(
            ".modal-close"
        );


    if (closeButton) {

        setTimeout(
            function () {

                closeButton.focus();

            },
            100
        );

    }

}


/* =========================================================
   28. إغلاق Modal
   ========================================================= */

function closeModal(modal) {


    if (!modal) {

        return;

    }


    modal.classList.remove(
        "active"
    );


    modal.setAttribute(
        "aria-hidden",
        "true"
    );


    const activeModal =
        document.querySelector(
            ".project-modal.active"
        );


    if (!activeModal) {

        document.body.classList.remove(
            "modal-open"
        );

    }

}


/* =========================================================
   29. حركة ظهور المشاريع
   ========================================================= */

function initializeCardAnimation() {


    const projectCards =
        document.querySelectorAll(
            ".project-card"
        );


    if (
        "IntersectionObserver"
        in window
    ) {


        const cardObserver =
            new IntersectionObserver(
                function (
                    entries,
                    observer
                ) {

                    entries.forEach(
                        function (entry) {

                            if (
                                entry.isIntersecting
                            ) {

                                entry.target.classList.add(
                                    "card-visible"
                                );


                                observer.unobserve(
                                    entry.target
                                );

                            }

                        }
                    );

                },
                {
                    threshold: 0.15
                }
            );


        projectCards.forEach(
            function (card) {

                cardObserver.observe(
                    card
                );

            }
        );

    }
    else {

        projectCards.forEach(
            function (card) {

                card.classList.add(
                    "card-visible"
                );

            }
        );

    }

}


/* =========================================================
   30. Smooth Scroll
   ========================================================= */

function initializeSmoothScroll() {


    const navigationLinks =
        document.querySelectorAll(
            'nav a[href^="#"], .hero a[href^="#"]'
        );


    navigationLinks.forEach(
        function (link) {

            link.addEventListener(
                "click",
                function (event) {

                    const targetId =
                        link.getAttribute(
                            "href"
                        );


                    if (
                        !targetId ||
                        targetId === "#"
                    ) {

                        return;

                    }


                    const target =
                        document.querySelector(
                            targetId
                        );


                    if (!target) {

                        return;

                    }


                    event.preventDefault();


                    target.scrollIntoView({
                        behavior: "smooth",
                        block: "start"
                    });

                }
            );

        }
    );

}


/* =========================================================
   31. تأثير Header عند النزول
   ========================================================= */

function initializeHeaderScroll() {


    const header =
        document.querySelector(
            "header"
        );


    if (!header) {

        return;

    }


    function updateHeader() {


        if (
            window.scrollY > 50
        ) {

            header.classList.add(
                "header-scrolled"
            );

        }
        else {

            header.classList.remove(
                "header-scrolled"
            );

        }

    }


    window.addEventListener(
        "scroll",
        updateHeader,
        {
            passive: true
        }
    );


    updateHeader();

}


