function applySiteData() {


    /* -----------------------------------------------------
       عنوان الصفحة
       ----------------------------------------------------- */

    document.title = SITE_DATA.pageTitle;


    /* -----------------------------------------------------
       اسم الموقع في الهيدر
       ----------------------------------------------------- */

    const siteNameElements =
        document.querySelectorAll(
            "[data-site-name]"
        );


    siteNameElements.forEach(function (element) {

        element.textContent =
            SITE_DATA.siteName;

    });


    /* -----------------------------------------------------
       اسم المستخدم
       ----------------------------------------------------- */

    const nameElements =
        document.querySelectorAll(
            "[data-user-name]"
        );


    nameElements.forEach(function (element) {

        element.textContent =
            SITE_DATA.name;

    });


    /* -----------------------------------------------------
       الصورة الشخصية
       ----------------------------------------------------- */

    const profileImages =
        document.querySelectorAll(
            "[data-profile-image]"
        );


    profileImages.forEach(function (image) {

        image.src =
            SITE_DATA.profileImage;

        image.alt =
            "الصورة الشخصية لـ " +
            SITE_DATA.name;

    });


    /* -----------------------------------------------------
       الوصف الشخصي
       ----------------------------------------------------- */

    const introductionElements =
        document.querySelectorAll(
            "[data-introduction]"
        );


    introductionElements.forEach(function (element) {

        element.textContent =
            SITE_DATA.introduction;

    });


    /* -----------------------------------------------------
       البريد الإلكتروني
       ----------------------------------------------------- */

    const emailElements =
        document.querySelectorAll(
            "[data-email]"
        );


    emailElements.forEach(function (element) {

        element.textContent =
            SITE_DATA.email;

        element.href =
            "mailto:" + SITE_DATA.email;

    });

}


