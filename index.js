/* =========================================================
   18. إنشاء المشاريع داخل الصفحة
   ========================================================= */

function renderProjects(
    projects,
    sectionId
) {


    const section =
        document.getElementById(sectionId);


    if (!section) {

        console.warn(
            "Section not found:",
            sectionId
        );

        return;

    }


    const grid =
        section.querySelector(
            ".projects-grid"
        );


    if (!grid) {

        console.warn(
            "Projects grid not found:",
            sectionId
        );

        return;

    }


    /* -----------------------------------------------------
       حذف المشاريع القديمة الموجودة في HTML
       حتى لا تتكرر المشاريع
       ----------------------------------------------------- */

    grid.innerHTML = "";


    /* -----------------------------------------------------
       إنشاء كل مشروع
       ----------------------------------------------------- */

    projects.forEach(function (project) {

        const card =
            createProjectCard(project);


        grid.appendChild(card);


        const modal =
            createProjectModal(project);


        document.body.appendChild(modal);

    });

}


/* =========================================================
   19. إنشاء بطاقة المشروع
   ========================================================= */

function createProjectCard(project) {


    const article =
        document.createElement("article");


    article.className =
        "project-card";


    article.dataset.category =
        project.category;


    article.dataset.projectId =
        project.id;


    /* -----------------------------------------------------
       الصورة
       ----------------------------------------------------- */

    const image =
        document.createElement("img");


    image.src =
        project.image;


    image.alt =
        project.name;


    /* -----------------------------------------------------
       محتوى البطاقة
       ----------------------------------------------------- */

    const content =
        document.createElement("div");


    content.className =
        "card-content";


    /* -----------------------------------------------------
       نوع المشروع
       ----------------------------------------------------- */

    const category =
        document.createElement("span");


    category.className =
        "project-category";


    category.textContent =
        project.category;


    /* -----------------------------------------------------
       اسم المشروع
       ----------------------------------------------------- */

    const title =
        document.createElement("h3");


    title.textContent =
        project.name;


    /* -----------------------------------------------------
       الوصف
       ----------------------------------------------------- */

    const description =
        document.createElement("p");


    description.textContent =
        project.shortDescription;


    /* -----------------------------------------------------
       زر التفاصيل
       ----------------------------------------------------- */

    const button =
        document.createElement("button");


    button.type =
        "button";


    button.className =
        "btn btn-small project-details-btn";


    button.dataset.project =
        project.id;


    button.textContent =
        "عرض التفاصيل";


    /* -----------------------------------------------------
       تجميع العناصر
       ----------------------------------------------------- */

    content.appendChild(category);

    content.appendChild(title);

    content.appendChild(description);

    content.appendChild(button);


    article.appendChild(image);

    article.appendChild(content);


    return article;

}


