function createProjectModal(project) {


    const modal =
        document.createElement("div");


    modal.className =
        "project-modal";


    modal.id =
        project.id;


    modal.setAttribute(
        "aria-hidden",
        "true"
    );


    /* -----------------------------------------------------
       الخلفية
       ----------------------------------------------------- */

    const overlay =
        document.createElement("div");


    overlay.className =
        "modal-overlay";


    /* -----------------------------------------------------
       محتوى النافذة
       ----------------------------------------------------- */

    const modalContent =
        document.createElement("div");


    modalContent.className =
        "modal-content";


    modalContent.setAttribute(
        "role",
        "dialog"
    );


    modalContent.setAttribute(
        "aria-modal",
        "true"
    );


    /* -----------------------------------------------------
       زر الإغلاق
       ----------------------------------------------------- */

    const closeButton =
        document.createElement("button");


    closeButton.type =
        "button";


    closeButton.className =
        "modal-close";


    closeButton.setAttribute(
        "aria-label",
        "إغلاق"
    );


    closeButton.innerHTML =
        "&times;";


    /* -----------------------------------------------------
       الصورة الرئيسية
       ----------------------------------------------------- */

    const mainImage =
        document.createElement("img");


    mainImage.src =
        project.image;


    mainImage.alt =
        project.name;


    mainImage.className =
        "modal-main-image";


    /* -----------------------------------------------------
       جسم النافذة
       ----------------------------------------------------- */

    const body =
        document.createElement("div");


    body.className =
        "modal-body";


    /* -----------------------------------------------------
       نوع المشروع
       ----------------------------------------------------- */

    const category =
        document.createElement("span");


    category.className =
        "project-category";


    category.textContent =
        project.category;


    /* -----------------------------------------------------
       اسم المشروع
       ----------------------------------------------------- */

    const title =
        document.createElement("h2");


    title.textContent =
        project.name;


    body.appendChild(category);

    body.appendChild(title);


    /* =====================================================
       وصف المشروع
       ===================================================== */

    addModalHeading(
        body,
        "عن المشروع"
    );


    addModalParagraph(
        body,
        project.description
    );


    /* =====================================================
       آلية العمل
       ===================================================== */

    addModalHeading(
        body,
        project.category === "IoT Project"
            ? "آلية عمل المشروع"
            : "آلية العمل"
    );


    addModalParagraph(
        body,
        project.howItWorks
    );


    /* =====================================================
       المكونات
       ===================================================== */

    if (
        project.components &&
        project.components.length > 0
    ) {

        addModalHeading(
            body,
            "المكونات المستخدمة"
        );


        addList(
            body,
            project.components
        );

    }


    /* =====================================================
       التقنيات / البرمجيات
       ===================================================== */

    if (
        project.technologies &&
        project.technologies.length > 0
    ) {

        addModalHeading(
            body,
            "التقنيات المستخدمة"
        );


        addList(
            body,
            project.technologies
        );

    }


    if (
        project.software &&
        project.software.length > 0
    ) {

        addModalHeading(
            body,
            "البرمجيات والتقنيات"
        );


        addList(
            body,
            project.software
        );

    }


    /* =====================================================
       معرض الصور
       ===================================================== */

    addModalHeading(
        body,
        "صور المشروع"
    );


    const gallery =
        document.createElement("div");


    gallery.className =
        "project-gallery";


    if (
        project.gallery &&
        project.gallery.length > 0
    ) {

        project.gallery.forEach(
            function (imagePath, index) {

                const image =
                    document.createElement("img");


                image.src =
                    imagePath;


                image.alt =
                    project.name +
                    " - صورة " +
                    (index + 1);


                gallery.appendChild(image);

            }
        );

    }


    body.appendChild(gallery);


    /* =====================================================
       رابط المشروع

       ⭐ ملاحظة مهمة ⭐
       تم إلغاء ميزة الرابط بالكامل لمشاريع IoT.
       الرابط يظهر فقط لمشاريع Web Development.
       ===================================================== */

    if (
        project.category === "Web Development"
    ) {

        const projectLink =
            document.createElement("a");


        projectLink.className =
            "btn";


        projectLink.target =
            "_blank";


        projectLink.rel =
            "noopener noreferrer";


        projectLink.textContent =
            "زيارة الموقع";


        /* -------------------------------------------------
           الرابط مأخوذ مباشرة من بيانات المشروع في JS
           ------------------------------------------------- */

        if (
            project.link &&
            !project.link.startsWith("ضع رابط")
        ) {

            projectLink.href =
                project.link;

        }
        else {

            projectLink.href =
                "#";

            projectLink.addEventListener(
                "click",
                function (event) {

                    event.preventDefault();


                    alert(
                        "رابط هذا المشروع لم تتم إضافته بعد."
                    );

                }
            );

        }


        body.appendChild(projectLink);

    }


    /* =====================================================
       تجميع النافذة
       ===================================================== */

    modalContent.appendChild(
        closeButton
    );


    modalContent.appendChild(
        mainImage
    );


    modalContent.appendChild(
        body
    );


    modal.appendChild(
        overlay
    );


    modal.appendChild(
        modalContent
    );


    return modal;

}


